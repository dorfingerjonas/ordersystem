-- =====================================================================
-- Ordersystem – product groups (variants like "Apfel Mineral 0,5l")
-- Run AFTER 20261120_02_rls.sql. Safe to re-run (idempotent).
--
-- A group only describes how its variants are built (attributes, price
-- grid, surcharges). Every variant is still a normal row in "product",
-- so orders, the insert_ordered_products trigger, cashing up, revenue
-- and the printer service keep working unchanged.
-- =====================================================================

create table if not exists public.product_group (
  id bigint generated by default as identity not null,
  name text not null,
  category bigint not null,
  ordering bigint generated by default as identity not null,
  -- [{"id": "a1", "name": "Sorte", "values": ["Apfel", "Orange"]}, ...] (1-3 entries)
  attributes jsonb not null default '[]'::jsonb,
  -- price grid in EUR, key = JSON array of the price attribute values, e.g. "[\"Mineral\",\"0,5l\"]"
  prices jsonb not null default '{}'::jsonb,
  -- surcharge in EUR per value of the first attribute (only with 2+ attributes)
  surcharges jsonb not null default '{}'::jsonb,
  -- variant keys switched off ("gibt es nicht")
  excluded jsonb not null default '[]'::jsonb,
  -- true: product name = "<group name> <values>", false: "<values>"
  prefix_name boolean not null default false,
  constraint product_group_pkey primary key (id),
  constraint product_group_category_fkey foreign key (category) references public.category (id)
    on update cascade on delete restrict
) tablespace pg_default;

-- variant products point to their group; deleting a group keeps the products (and their revenue)
alter table public.product
  add column if not exists product_group bigint null;

-- {"<attribute id>": "<value>", ...}
alter table public.product
  add column if not exists variant jsonb null;

-- hidden everywhere except in revenue / already ordered items (variant switched off or removed)
alter table public.product
  add column if not exists archived boolean not null default false;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'product_product_group_fkey') then
    alter table public.product
      add constraint product_product_group_fkey foreign key (product_group) references public.product_group (id)
        on update cascade on delete set null;
  end if;
end $$;

create index if not exists product_product_group_idx on public.product (product_group);

-- ---------------------------------------------------------------------
-- RLS: same rules as the other master data tables
-- ---------------------------------------------------------------------
alter table public.product_group enable row level security;

drop policy if exists "read for authenticated" on public.product_group;
drop policy if exists "admin insert" on public.product_group;
drop policy if exists "admin update" on public.product_group;
drop policy if exists "admin delete" on public.product_group;

create policy "read for authenticated" on public.product_group
  for select to authenticated using (true);
create policy "admin insert" on public.product_group
  for insert to authenticated with check (public.is_admin());
create policy "admin update" on public.product_group
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin delete" on public.product_group
  for delete to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------
-- Realtime
-- ---------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'product_group') then
    alter publication supabase_realtime add table public.product_group;
  end if;
end $$;
