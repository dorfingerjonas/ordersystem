-- ---------------------------------------------------------------------
-- 1) Areas (table sections like "Reihe 1", "Bereich O")
-- ---------------------------------------------------------------------
create table if not exists public.area (
  id bigint generated by default as identity not null,
  name text not null,
  ordering bigint generated by default as identity not null,
  constraint area_pkey primary key (id)
) tablespace pg_default;

alter table public.tables
  add column if not exists area bigint null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'tables_area_fkey') then
    alter table public.tables
      add constraint tables_area_fkey foreign key (area) references public.area (id)
        on update cascade on delete set null;
  end if;
end $$;

-- Seed: create one area per first character of the table nr and assign
-- the tables (only runs while the area table is still empty).
-- Digits become "Reihe <x>", letters become "Bereich <x>". Rename later in the app.
do $$
declare
  prefix text;
  area_id bigint;
begin
  if (select count(*) from public.area) = 0 then
    for prefix in
      select p from (
        select upper(left(nr, 1)) as p, min(ordering) as o
        from public.tables
        group by upper(left(nr, 1))
      ) s order by s.o
    loop
      insert into public.area (name)
      values (case when prefix ~ '^[0-9]$' then 'Reihe ' || prefix else 'Bereich ' || prefix end)
      returning id into area_id;

      update public.tables set area = area_id where upper(left(nr, 1)) = prefix;
    end loop;
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 2) Sold-out toggle for products
-- ---------------------------------------------------------------------
alter table public.product
  add column if not exists available boolean not null default true;

-- ---------------------------------------------------------------------
-- 3) Print jobs (test print, later maybe re-print)
--    The client inserts a job, the printer service prints it and
--    sets status to DONE or FAILED (+ message).
-- ---------------------------------------------------------------------
create table if not exists public.print_job (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  device bigint not null,
  type text not null default 'TEST',
  status text not null default 'PENDING',
  message text null,
  finished_at timestamp with time zone null,
  constraint print_job_pkey primary key (id),
  constraint print_job_device_fkey foreign key (device) references public.device (id)
    on update cascade on delete cascade,
  constraint print_job_type_check check (type in ('TEST')),
  constraint print_job_status_check check (status in ('PENDING', 'DONE', 'FAILED'))
) tablespace pg_default;

create index if not exists print_job_status_idx on public.print_job (status);

