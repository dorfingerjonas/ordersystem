    alter publication supabase_realtime add table public.area;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'print_job') then
    alter publication supabase_realtime add table public.print_job;
  end if;
end $$;
